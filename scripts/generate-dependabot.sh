#!/usr/bin/env bash
# saas-blind-security - generate a dependabot.yml for the ecosystems actually present.
# Created and maintained by IbrahimCodeur - https://github.com/IbrahimCodeur
# SPDX-License-Identifier: MIT
#
# Usage: generate-dependabot.sh [PROJECT_DIR] > .github/dependabot.yml
# Only ecosystems with a real manifest are emitted (Dependabot fails on missing manifests).

set -uo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
. "$SCRIPT_DIR/lib/common.sh"
TARGET="${1:-.}"
INTERVAL="${SBS_DEPENDABOT_INTERVAL:-weekly}"
LIMIT="${SBS_DEPENDABOT_PR_LIMIT:-5}"
COOLDOWN="${SBS_DEPENDABOT_COOLDOWN_DAYS:-7}"

cat <<HDR
# Generated by saas-blind-security (https://github.com/IbrahimCodeur/saas-blind-security)
# Docs: https://docs.github.com/code-security/dependabot/working-with-dependabot/dependabot-options-reference
version: 2
updates:
HDR
"$SCRIPT_DIR/detect-stack.sh" --dependabot-ecosystems "$TARGET" | sort -u | while read -r eco dir; do
  [ -z "$eco" ] && continue
  cat <<ENTRY
  - package-ecosystem: "$eco"
    directory: "$dir"
    schedule:
      interval: "$INTERVAL"
    open-pull-requests-limit: $LIMIT
    cooldown:
      default-days: $COOLDOWN
    labels:
      - "dependencies"
      - "security"
ENTRY
  case "$eco" in
    npm|composer|pip)
      cat <<'GROUP'
    groups:
      minor-and-patch:
        update-types:
          - "minor"
          - "patch"
GROUP
      ;;
  esac
done
