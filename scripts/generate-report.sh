#!/usr/bin/env bash
# saas-blind-security - render a Markdown security report from a results directory.
# Created and maintained by IbrahimCodeur - https://github.com/IbrahimCodeur
# SPDX-License-Identifier: MIT
#
# Usage: generate-report.sh RESULTS_DIR [--fail-on LEVEL] [--project DIR] > report.md
# RESULTS_DIR must contain findings.json and tools.json produced by security-check.sh.

set -uo pipefail
# shellcheck source=lib/common.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib/common.sh"
have jq || die "jq is required"

DIR=""; FAIL_ON="HIGH"; PROJECT=""
while [ $# -gt 0 ]; do
  case "$1" in
    --fail-on) FAIL_ON="${2:-HIGH}"; shift ;;
    --project) PROJECT="${2:-}"; shift ;;
    -h|--help) sed -n '2,8p' "$0"; exit 0 ;;
    *) DIR="$1" ;;
  esac
  shift
done
[ -n "$DIR" ] || die "Usage: generate-report.sh RESULTS_DIR"
F="$DIR/findings.json"; T="$DIR/tools.json"
[ -f "$F" ] && [ -f "$T" ] || die "$DIR does not contain findings.json and tools.json"

count() { jq --arg s "$1" '[.[] | select(.severity==$s)] | length' "$F"; }
TOTAL="$(jq length "$F")"
PROJECT_NAME="$(basename "${PROJECT:-$(pwd)}")"
COMMIT="$( [ -n "$PROJECT" ] && git -C "$PROJECT" rev-parse --short HEAD 2>/dev/null || echo "n/a")"

cat <<HDR
# Security Report — $PROJECT_NAME

| Field | Value |
|---|---|
| Generated (UTC) | $(date -u +%Y-%m-%dT%H:%M:%SZ) |
| Framework | saas-blind-security v$SBS_VERSION |
| Commit | $COMMIT |
| Blocking threshold | $FAIL_ON |
| Total findings | $TOTAL |

> **Read this first.** Every finding below is **unverified** output from automated tools.
> Each one must be confirmed, classified as a false positive, or marked "not verified" by a reviewer.
> Tools that did not run are listed in *Coverage*: their risk areas were **not checked**.
> An empty report does **not** prove the application is secure.

## Summary

| Severity | Count |
|---|---|
| CRITICAL | $(count CRITICAL) |
| HIGH | $(count HIGH) |
| MEDIUM | $(count MEDIUM) |
| LOW | $(count LOW) |
| INFO | $(count INFO) |

## Coverage

| Tool | Status | Detail | Findings |
|---|---|---|---|
HDR
jq -r '.[] | [.tool, .status, (.detail|gsub("\\|";"\\\\|")), ((.findings // "—")|tostring)] | "| " + join(" | ") + " |"' "$T"

cat <<'MID'

### Not covered by automated tools

Automated scanners are weak at business logic. Review these manually (see `docs/security-checklist.md`):
broken access control and IDOR/BOLA, cross-tenant isolation, payment and billing logic, race conditions,
quota and rate-limit enforcement, account deletion and data export, backup protection, audit logging.

## Findings
MID

if [ "$TOTAL" -eq 0 ]; then
  echo
  echo "_No finding was reported by the tools that ran. This is not proof of security._"
else
  for s in CRITICAL HIGH MEDIUM LOW INFO; do
    n="$(count "$s")"; [ "$n" -eq 0 ] && continue
    echo; echo "### $s ($n)"; echo
    echo "| ID | Tool | Rule | Location | Title | Status |"
    echo "|---|---|---|---|---|---|"
    jq -r --arg s "$s" '.[] | select(.severity==$s)
      | [.id, .tool, (.rule // "-"), ((.file // "-") + (if .line then ":" + (.line|tostring) else "" end)), .title, .status]
      | map(tostring | gsub("\\|";"\\\\|") | gsub("<";"&lt;") | gsub(">";"&gt;") | gsub("\n";" "))
      | "| " + join(" | ") + " |"' "$F"
  done
  echo
  echo "### Details"
  jq -r '.[] | select(.detail != null and .detail != "") | "- **\(.id)** — \(.detail | gsub("\n";" "))"' "$F" | head -n 500
fi

cat <<'TAIL'

## Triage instructions

For each finding, record one of: **Confirmed**, **False positive** (with justification), **Risk accepted** (owner + expiry),
or **Not verified** (why). Confirmed issues go into a remediation plan (`templates/remediation-plan.md`) with:
impact, exploitation conditions, technical proof, recommended fix, and the test that proves the fix.

## Raw results

Scanner outputs are stored next to this report in `raw/` (JSON / SARIF / HTML). They may contain sensitive paths:
do not publish them.

---
Report generated by saas-blind-security — created and maintained by IbrahimCodeur.
TAIL
